// dsh-pixelfly — the model-facing tools.
//
// Three tools, deliberately small: generate, inspect configuration, and check the
// upstream. The definitions are plain objects (no import from the Harness packages)
// so this plugin loads from any directory without a build step.

import { activeKeys, maskKey, pluginRoot, publicConfig, readConfig, writeConfig } from './config.js'
import { generateImages, KNOWN_MODELS } from './generate.js'
import { listModels, KeyPool } from './upstream.js'
import { listGenerated } from './images.js'

const MODEL_ENUM = [...KNOWN_MODELS]

function renderText(text) {
  return [{ type: 'text', text }]
}

function summarize(result) {
  const lines = [
    `Generated ${result.n} image${result.n === 1 ? '' : 's'} with ${result.model}.`,
    `size ${result.size} · ${result.attempts} upstream attempt${result.attempts === 1 ? '' : 's'} · ${(result.elapsedMs / 1000).toFixed(1)}s`,
  ]
  for (const image of result.images) {
    const dimensions = image.width > 0 ? `${image.width}×${image.height}` : 'unknown size'
    const where = image.path ? image.path : '(not written to disk)'
    lines.push(`- ${image.format.toUpperCase()} ${dimensions}, ${(image.bytes / 1024).toFixed(0)} KiB → ${where}`)
  }
  if (result.trace && result.trace.length > 1) {
    lines.push('', 'Attempts:')
    for (const step of result.trace) {
      const detail = step.status > 0 ? `HTTP ${step.status}` : step.code
      lines.push(`  ${step.attempt}. ${step.keyId} → ${detail} (${step.ms} ms)${step.message ? ` — ${step.message}` : ''}`)
    }
  }
  return lines.join('\n')
}

/** Save generated bytes into the attachment store so the chat can show them inline. */
async function admitImages(ctx, images, prompt) {
  let attachments
  try { attachments = ctx.get('attachments') } catch { attachments = undefined }
  if (!attachments || typeof attachments.saveImages !== 'function') return []
  const inputs = images
    .filter((image) => image.data && image.mediaType)
    .map((image, index) => ({
      data: new Uint8Array(image.data),
      mediaType: image.mediaType,
      name: image.path ? image.path.split(/[\\/]/).pop() : `pixelfly-${index + 1}.png`,
    }))
  if (inputs.length === 0) return []
  try {
    const refs = await attachments.saveImages(inputs)
    return Array.from(refs ?? [])
  } catch {
    return []
  }
}

export function createTools(ctx) {
  const generate = {
    name: 'pixelfly_generate',
    description: 'Generate an image from a text prompt with the configured Pixelfly upstream (SenseNova U1.5). Returns the saved file path plus the image itself. Supports multiple configured API keys with automatic rotation and exponential backoff on rate limits and transient upstream failures.',
    parameters: {
      type: 'object',
      properties: {
        prompt: { type: 'string', description: 'What to draw. Be specific about subject, composition, lighting and style.' },
        model: { type: 'string', enum: MODEL_ENUM, description: 'Model id. Defaults to the configured default (sensenova-u1.5-fast).' },
        size: { type: 'string', description: 'Output size such as 1024x1024, or "auto". Defaults to the configured size.' },
        n: { type: 'integer', description: 'How many images to generate (1-4). Defaults to 1.' },
        watermark: { type: 'boolean', description: 'Ask the upstream to burn in a watermark. Defaults to false.' },
        promptExtend: { type: 'boolean', description: 'Let the upstream expand the prompt. Defaults to true.' },
      },
      required: ['prompt'],
    },
    output: {
      schema: {
        type: 'object',
        properties: {
          ok: { type: 'boolean' },
          model: { type: 'string' },
          prompt: { type: 'string' },
          size: { type: 'string' },
          n: { type: 'integer' },
          attempts: { type: 'integer' },
          elapsedMs: { type: 'integer' },
          images: {
            type: 'array',
            items: {
              type: 'object',
              properties: {
                path: { type: 'string' },
                mediaType: { type: 'string' },
                format: { type: 'string' },
                width: { type: 'integer' },
                height: { type: 'integer' },
                bytes: { type: 'integer' },
              },
            },
          },
          attachments: { type: 'array', items: { type: 'object' } },
          trace: { type: 'array', items: { type: 'object' } },
        },
        required: ['ok', 'model', 'n'],
      },
      render: (_args, value) => {
        const blocks = renderText(summarize(value))
        for (const attachment of value.attachments ?? []) {
          if (attachment && typeof attachment === 'object' && typeof attachment.attachmentId === 'string') {
            blocks.push({ type: 'image', attachment })
          }
        }
        return blocks
      },
    },
    async execute(args, exec) {
      const result = await generateImages(args, { signal: exec?.signal })
      const refs = await admitImages(ctx, result.images, result.prompt)
      return {
        ok: result.ok,
        model: result.model,
        prompt: result.prompt,
        size: result.size,
        n: result.n,
        attempts: result.attempts,
        elapsedMs: result.elapsedMs,
        images: result.images.map(({ data: _data, ...rest }) => rest),
        attachments: refs,
        trace: result.trace,
      }
    },
    isConcurrencySafe: () => true,
    timeoutMs: 300000,
  }

  const configTool = {
    name: 'pixelfly_config',
    description: 'Read or update the Pixelfly plugin configuration: upstream base URL, API keys, default model, retry policy and output directory. Secrets are returned masked; pass a new value to change a key.',
    parameters: {
      type: 'object',
      properties: {
        action: { type: 'string', enum: ['read', 'setBaseUrl', 'setDefaultModel', 'addKey', 'removeKey', 'setRetry', 'setOutputDir'], description: 'What to do. Defaults to read.' },
        baseUrl: { type: 'string', description: 'For setBaseUrl: the upstream base URL, e.g. https://token.sensenova.cn/v1' },
        model: { type: 'string', description: 'For setDefaultModel: the default model id.' },
        key: { type: 'string', description: 'For addKey: the API key value.' },
        label: { type: 'string', description: 'For addKey: a human label for the key.' },
        keyId: { type: 'string', description: 'For removeKey: the key id to drop.' },
        maxAttempts: { type: 'integer', description: 'For setRetry: total attempts including the first (1-12).' },
        baseDelayMs: { type: 'integer', description: 'For setRetry: first backoff delay in milliseconds.' },
        dir: { type: 'string', description: 'For setOutputDir: absolute directory for generated files.' },
      },
    },
    output: {
      schema: { type: 'object', properties: { ok: { type: 'boolean' }, config: { type: 'object' }, message: { type: 'string' } }, required: ['ok'] },
      render: (_args, value) => renderText(value.message ?? JSON.stringify(value.config, null, 2)),
    },
    async execute(args) {
      const action = args?.action ?? 'read'
      if (action === 'setBaseUrl') {
        if (typeof args.baseUrl !== 'string' || !/^https?:\/\//i.test(args.baseUrl)) throw new Error('baseUrl must be an http(s) URL')
        writeConfig({ upstream: { baseUrl: args.baseUrl.trim() } })
        return { ok: true, message: `Upstream base URL set to ${args.baseUrl.trim()}` }
      }
      if (action === 'setDefaultModel') {
        if (typeof args.model !== 'string' || args.model.trim().length === 0) throw new Error('model is required')
        writeConfig({ models: { default: args.model.trim() } })
        return { ok: true, message: `Default model set to ${args.model.trim()}` }
      }
      if (action === 'addKey') {
        if (typeof args.key !== 'string' || args.key.trim().length < 8) throw new Error('key is required')
        const config = readConfig()
        const id = `key-${Date.now().toString(36)}`
        const next = [...config.apiKeys, { id, label: args.label || `Key ${config.apiKeys.length + 1}`, enabled: true, weight: 1, key: args.key.trim() }]
        writeConfig({ apiKeys: next })
        return { ok: true, message: `Added API key ${maskKey(args.key.trim())} as ${id}` }
      }
      if (action === 'removeKey') {
        if (typeof args.keyId !== 'string') throw new Error('keyId is required')
        const config = readConfig()
        const next = config.apiKeys.filter((entry) => entry.id !== args.keyId)
        writeConfig({ apiKeys: next })
        return { ok: true, message: `Removed ${config.apiKeys.length - next.length} key(s)` }
      }
      if (action === 'setRetry') {
        const patch = {}
        if (Number.isFinite(Number(args.maxAttempts))) patch.maxAttempts = Math.max(1, Math.min(12, Math.round(Number(args.maxAttempts))))
        if (Number.isFinite(Number(args.baseDelayMs))) patch.baseDelayMs = Math.max(50, Math.round(Number(args.baseDelayMs)))
        writeConfig({ retry: patch })
        return { ok: true, message: `Retry policy updated: ${JSON.stringify(patch)}` }
      }
      if (action === 'setOutputDir') {
        if (typeof args.dir !== 'string' || args.dir.trim().length === 0) throw new Error('dir is required')
        writeConfig({ output: { dir: args.dir.trim() } })
        return { ok: true, message: `Output directory set to ${args.dir.trim()}` }
      }
      return { ok: true, config: publicConfig(), message: `Pixelfly config at ${pluginRoot()}` }
    },
    isConcurrencySafe: () => false,
  }

  const status = {
    name: 'pixelfly_status',
    description: 'Report the Pixelfly upstream, configured keys (masked), retry policy and recent generated files, and optionally probe the upstream for its model list and a live key check.',
    parameters: {
      type: 'object',
      properties: {
        probe: { type: 'boolean', description: 'Also call the upstream /models endpoint with the first usable key.' },
        recent: { type: 'integer', description: 'How many recent files to list (default 5).' },
      },
    },
    output: {
      schema: {
        type: 'object',
        properties: {
          ok: { type: 'boolean' },
          baseUrl: { type: 'string' },
          keys: { type: 'array', items: { type: 'object' } },
          retry: { type: 'object' },
          models: { type: 'array', items: { type: 'object' } },
          recent: { type: 'array', items: { type: 'object' } },
          error: { type: 'string' },
        },
        required: ['ok'],
      },
      render: (_args, value) => {
        const lines = [`Pixelfly upstream: ${value.baseUrl}`, `Keys: ${value.keys.length} configured`]
        for (const key of value.keys) lines.push(`  · ${key.label} ${key.masked}${key.enabled === false ? ' (disabled)' : ''}`)
        lines.push(`Retry: up to ${value.retry?.maxAttempts ?? '?'} attempts, base ${value.retry?.baseDelayMs ?? '?'} ms`)
        if (value.models) lines.push(`Upstream models: ${value.models.map((row) => row.id).join(', ') || '(none)'}`)
        if (value.error) lines.push(`Probe error: ${value.error}`)
        if (value.recent?.length) {
          lines.push('Recent files:')
          for (const row of value.recent) lines.push(`  · ${row.path} (${(row.bytes / 1024).toFixed(0)} KiB)`)
        }
        return renderText(lines.join('\n'))
      },
    },
    async execute(args) {
      const config = readConfig()
      const keys = activeKeys(config).map((entry) => ({ id: entry.id, label: entry.label, masked: maskKey(entry.key), enabled: entry.enabled !== false }))
      const value = {
        ok: true,
        baseUrl: config.upstream.baseUrl,
        keys,
        retry: config.retry,
        models: undefined,
        recent: listGenerated(Number(args?.recent ?? 5)),
      }
      if (args?.probe === true) {
        try {
          value.models = await listModels({ config })
        } catch (error) {
          value.error = error.message
        }
      }
      return value
    },
    isConcurrencySafe: () => true,
  }

  return [generate, configTool, status]
}

export { KeyPool }
